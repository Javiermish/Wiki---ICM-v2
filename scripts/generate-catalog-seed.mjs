// Node >=22.18 native TypeScript stripping. No DB connection or dependencies.
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { demoCatalog } from '../src/fixtures/catalog.ts';

const destination = new URL('../supabase/migrations/202610230002_catalog_seed.sql', import.meta.url);
const inspectionDestination = new URL('../supabase/tests/inspect_catalog_seed.sql', import.meta.url);
assert.ok(process.argv.slice(2).every(argument => argument === '--check'), 'Only --check is accepted');
const literal = (value) => value === null ? 'null' : typeof value === 'number' ? String(value) : `'${value.replaceAll("'", "''")}'`;
const rows = (values) => values.map((row) => `  (${row.map(literal).join(', ')})`).join(',\n');
assert.equal(demoCatalog.courses.length, 9, 'Seed scope: exactly nine illustrative courses');
assert.equal(demoCatalog.electiveAreas.length, 5);
assert.equal(new Set(demoCatalog.courses.map(({ id }) => id)).size, 9);
const plans = [...new Set(demoCatalog.courses.map(({ curriculumId }) => curriculumId))];
assert.deepEqual(plans, ['plan-ilustrativo']);
const sql = `-- Generated by node scripts/generate-catalog-seed.mjs from src/fixtures/catalog.ts.
-- Illustrative data, NOT the official curriculum. Never overwrite existing edits.
begin;
insert into public.curricula(id,name) values ('plan-ilustrativo','Plan ilustrativo (no oficial)') on conflict do nothing;
insert into public.elective_areas(id,name,position) values
${rows(demoCatalog.electiveAreas.map((area, index) => [area.id, area.name, index]))}
on conflict do nothing;
insert into public.courses(id,slug,curriculum_id,name,code,description,kind,curricular_semester,elective_area_id,status) values
${rows(demoCatalog.courses.map((c) => [c.id,c.slug,c.curriculumId,c.name,c.code,c.description,c.kind,c.curricularSemester,c.electiveAreaId,c.status]))}
on conflict do nothing;
commit;
`;
const inspection = `-- Generated read-only verification of INITIAL seed. Run before administrative edits.
-- Existing edits are reported, never overwritten. Not a migration or a destructive test.
with expected(id,slug,curriculum_id,name,code,description,kind,curricular_semester,elective_area_id,status) as (values
${rows(demoCatalog.courses.map((c) => [c.id,c.slug,c.curriculumId,c.name,c.code,c.description,c.kind,c.curricularSemester,c.electiveAreaId,c.status]))}
)
select e.id, case when c.id is null then 'MISSING'
  when (c.slug,c.curriculum_id,c.name,c.code,c.description,c.kind,c.curricular_semester,c.elective_area_id,c.status)
    is distinct from (e.slug,e.curriculum_id,e.name,e.code,e.description,e.kind,e.curricular_semester,e.elective_area_id,e.status)
  then 'DIFFERS' else 'MATCH' end as verification
from expected e left join public.courses c on c.id=e.id order by e.id;
with expected(id,name,position) as (values
${rows(demoCatalog.electiveAreas.map((area, index) => [area.id, area.name, index]))}
)
select e.id, case when a.id is null then 'MISSING'
  when (a.name,a.position) is distinct from (e.name,e.position) then 'DIFFERS' else 'MATCH' end as verification
from expected e left join public.elective_areas a on a.id=e.id order by e.position;
`;
if (process.argv.includes('--check')) {
  assert.equal(await readFile(destination, 'utf8'), sql, 'Seed differs from fixtures; regenerate and review migration before applying');
  assert.equal(await readFile(inspectionDestination, 'utf8'), inspection, 'Seed inspection differs from fixtures');
  console.log('Catalog seed matches fixtures (9 courses, 5 areas).');
} else {
  await writeFile(destination, sql);
  await writeFile(inspectionDestination, inspection);
  console.log('Generated versioned catalog seed; no database accessed.');
}
